const messages = { en, fr };

export type Messages = Widen<typeof en>;

export function isLocale(value: string): value is Locale {
  return value === "en" || value === "fr";
}

export function getMessages(locale: Locale): Messages {
  return messages[locale];
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function term(messagesForLocale: Messages, value: string): string {
  const known = messagesForLocale.terms[value as keyof Messages["terms"]];
  return known ?? value.replaceAll("_", " ").replace(/^./, (char) => char.toUpperCase());
}

export function translateFlash(locale: Locale, value: string | undefined): string | undefined {
  if (!value) return undefined;
  const splitAt = value.indexOf(":");
  const code = splitAt === -1 ? value : value.slice(0, splitAt);
  const arg = splitAt === -1 ? "" : value.slice(splitAt + 1);
  const text = (messages[locale].flash as Record<string, string>)[code];
  if (!text) return value;
  return arg ? text.replaceAll("{date}", formatDate(arg, locale)) : text;
}

export function dateTag(locale: Locale): string {
  return locale === "fr" ? "fr-FR" : "en-GB";
}
